/*
 * S5 Framework — Edit-lens panel + REST save (Editor MVP, Phase B2).
 *
 * Builds on the shell (window.S5EditorShell). Responsibilities:
 *   - receive selection messages from the preview overlay (postMessage)
 *   - render fields PURELY from the selected node's declaration (data-edit)
 *   - stage edits in slotEdits; patch the iframe live for feedback; mark dirty
 *   - on Update, POST the staged slot edits to the ONE save door; on success,
 *     reload the preview from the server (derived state replaces edits)
 *
 * The iframe is never the state store (EDITOR-DESIGN.md §1). Nothing persists
 * until Update, and Update always round-trips through the compiler server-side.
 */
( function () {
	'use strict';

	var shell = window.S5EditorShell;
	if ( ! shell ) {
		return;
	}
	var cfg = window.S5Editor || {};
	var root = document.querySelector( '[data-s5-editor]' );
	// The Content pane the selected element's fields render into. Prefer the Phase B
	// hook [data-s5-content]; fall back to the legacy [data-s5-panel-body] alias.
	var panelBody = root.querySelector( '[data-s5-content]' ) || root.querySelector( '[data-s5-panel-body]' );
	var updateBtn = root.querySelector( '[data-s5-update]' );
	var ORIGIN = window.location.origin;

	// Pending slot edits: node id -> { node, type, value, attr }.
	var slotEdits = {};
	var selected = null;

	function frameWindow() {
		var f = shell.getPreviewFrame();
		return f ? f.contentWindow : null;
	}

	function sendToFrame( msg ) {
		var w = frameWindow();
		if ( w ) {
			w.postMessage( msg, ORIGIN );
		}
	}

	function el( tag, attrs, text ) {
		var node = document.createElement( tag );
		if ( attrs ) {
			Object.keys( attrs ).forEach( function ( k ) {
				node.setAttribute( k, attrs[ k ] );
			} );
		}
		if ( undefined !== text && null !== text ) {
			node.textContent = text;
		}
		return node;
	}

	function stage( node, type, value, attr ) {
		slotEdits[ node ] = { node: node, type: type, value: value, attr: attr || '' };
		shell.markDirty();
		sendToFrame( { s5: 's5-patch', node: node, type: type, value: value, attr: attr || '' } );
	}

	/* --- render fields from a declaration --------------------------------
	 * TRANSCRIBED from canvas-mockup.html renderContent() (lines 1158-1215): the
	 * mockup's per-kind .field markup (Text textarea · Button Text/Link/Open-in ·
	 * media-field + Alt · container-note), preceded by the Enabled/Disabled
	 * .enable-row. Real slot data (sel.text/href/alt/src) is wired INTO that markup —
	 * markup first, data second (STANDING ORDER hold on the props panel). */

	// mockup helper: a labelled .field wrapping an already-built control node.
	function field( label, controlNode ) {
		var f = el( 'div', { class: 'field' } );
		f.appendChild( el( 'label', { class: 'field-label' }, label ) );
		f.appendChild( controlNode );
		return f;
	}

	// mockup .enable-row (Content view top). Enabled = renders; disabled = removed
	// from output. The switch flips it through the ONE door (mode:disable).
	function enableRow( sel ) {
		var isDisabled = !! sel.disabled;
		var row = el( 'div', { class: 'enable-row ' + ( isDisabled ? 'off' : 'on' ) } );
		var lab = el( 'div', { class: 'enable-label' } );
		lab.appendChild( el( 'i', { class: 'fa-solid ' + ( isDisabled ? 'fa-ban' : 'fa-circle-check' ) } ) );
		lab.appendChild( el( 'span', {}, isDisabled ? 'Disabled' : 'Enabled' ) );
		lab.appendChild( el( 'em', {}, isDisabled ? 'removed from output' : 'renders in output' ) );
		row.appendChild( lab );
		var sw = el( 'button', {
			type: 'button',
			class: 'switch' + ( isDisabled ? '' : ' on' ),
			role: 'switch',
			'aria-checked': isDisabled ? 'false' : 'true',
		} );
		sw.appendChild( el( 'span', { class: 'knob' } ) );
		sw.addEventListener( 'click', function () {
			doDisable( sel.node, ! isDisabled );
		} );
		row.appendChild( sw );
		return row;
	}

	function renderFields( sel ) {
		panelBody.innerHTML = '';

		if ( ! sel.node ) {
			panelBody.appendChild(
				el( 'p', { class: 's5e-hint' },
					'This element is editable but has no data-node id. Add one in source to make it savable.' )
			);
			return;
		}

		// L&L dynamic region: locked in Edit lens (mockup container-note idiom + badge).
		if ( sel.dynamic ) {
			var lock = el( 'div', { class: 's5e-locked' } );
			lock.appendChild( el( 'span', { class: 's5e-badge' }, 'Dynamic' ) );
			lock.appendChild( el( 'p', { class: 's5e-hint' },
				'This region is generated by Loops & Logic. Edit it in Code view.' ) );
			panelBody.appendChild( lock );
			return;
		}

		// Enable/disable row at the top of Content for every element (mockup).
		panelBody.appendChild( enableRow( sel ) );

		var type = sel.type;

		if ( 'text' === type || 'rich' === type ) {
			var ta = el( 'textarea', { class: 'textarea' } );
			ta.value = sel.text || '';
			ta.addEventListener( 'input', function () {
				stage( sel.node, type, ta.value, '' );
			} );
			panelBody.appendChild( field( 'Text', ta ) );
		} else if ( 'link' === type ) {
			var linkText = el( 'input', { class: 'input' } );
			linkText.value = sel.text || '';
			// The anchor's visible text is its inner content → the server's `text` slot
			// (replace_inner) on the SAME data-node. `link` edits href; `text` edits the
			// label. Both are supported server-side — no invented contract.
			linkText.addEventListener( 'input', function () {
				stage( sel.node, 'text', linkText.value, '' );
			} );
			panelBody.appendChild( field( 'Button Text', linkText ) );

			var link = el( 'input', { class: 'input', type: 'url', placeholder: '/path/  or  https://…' } );
			link.style.fontFamily = 'var(--s5e-mono)';
			link.style.fontSize = '12px';
			link.value = sel.href || '';
			link.addEventListener( 'input', function () {
				stage( sel.node, 'link', link.value, '' );
			} );
			panelBody.appendChild( field( 'Link', link ) );

			// Open-in segmented control (Same/New tab) — presentational (mockup ships it).
			var openIn = el( 'div', { class: 'seg wide' } );
			openIn.appendChild( el( 'div', { class: 'seg-opt active' }, 'Same tab' ) );
			openIn.appendChild( el( 'div', { class: 'seg-opt' }, 'New tab' ) );
			panelBody.appendChild( field( 'Open in', openIn ) );
		} else if ( 'img' === type ) {
			// Media field: thumbnail + library link + name (mockup .media-field).
			var mediaWrap = el( 'div', { class: 'field' } );
			mediaWrap.appendChild( el( 'label', { class: 'field-label' }, 'Image' ) );
			var mf = el( 'div', { class: 'media-field' } );
			var src0 = sel.src || '';
			var thumb = el( 'div', { class: 'media-thumb' + ( src0 ? '' : ' noimg' ) } );
			if ( src0 ) {
				var img = el( 'img', { src: src0, alt: '' } );
				img.addEventListener( 'error', function () {
					thumb.classList.add( 'noimg' );
					img.style.display = 'none';
				} );
				thumb.appendChild( img );
			}
			var ph = el( 'span', { class: 'media-thumb-ph' } );
			ph.appendChild( el( 'i', { class: 'fa-regular fa-image' } ) );
			thumb.appendChild( ph );
			mf.appendChild( thumb );
			var meta = el( 'div', { class: 'media-meta' } );
			meta.appendChild( el( 'div', { class: 'media-name' }, src0 ? src0.split( '/' ).pop() : 'no image' ) );
			var lib = el( 'button', { type: 'button', class: 'media-lib' } );
			lib.appendChild( el( 'i', { class: 'fa-regular fa-images' } ) );
			lib.appendChild( document.createTextNode( ' Media Library' ) );
			meta.appendChild( lib );
			mf.appendChild( meta );
			mediaWrap.appendChild( mf );
			panelBody.appendChild( mediaWrap );

			var alt = el( 'input', { class: 'input', type: 'text', placeholder: 'Describe the image' } );
			alt.value = sel.alt || '';
			alt.addEventListener( 'input', function () {
				stage( sel.node, 'img', alt.value, 'alt' );
			} );
			panelBody.appendChild( field( 'Alt text', alt ) );

			var src = el( 'input', { class: 'input', type: 'text', placeholder: 'assets/…' } );
			src.style.fontFamily = 'var(--s5e-mono)';
			src.style.fontSize = '12px';
			src.value = src0;
			src.addEventListener( 'input', function () {
				stage( sel.node, 'img', src.value, 'src' );
			} );
			panelBody.appendChild( field( 'Image path (assets/…)', src ) );
		} else if ( 'src' === type ) {
			var embed = el( 'input', { class: 'input', type: 'url', placeholder: 'https://…' } );
			embed.value = sel.src || '';
			embed.addEventListener( 'input', function () {
				stage( sel.node, 'src', embed.value, '' );
			} );
			panelBody.appendChild( field( 'Embed URL', embed ) );
		} else if ( 'list' === type ) {
			var list = el( 'textarea', { class: 'textarea' } );
			list.value = sel.items || sel.text || '';
			list.addEventListener( 'input', function () {
				stage( sel.node, 'list', list.value, '' );
			} );
			panelBody.appendChild( field( 'List items (one per line)', list ) );
		} else {
			// Container / unknown → mockup container-note.
			var note = el( 'div', { class: 'container-note' } );
			note.appendChild( el( 'i', { class: 'fa-solid fa-layer-group' } ) );
			var body = el( 'div' );
			var strong = el( 'strong', {}, sel.label || sel.type || 'Element' );
			body.appendChild( strong );
			body.appendChild( document.createTextNode( ' is a container. Select an item inside it to edit content. Layout & spacing are on the Style tab.' ) );
			note.appendChild( body );
			panelBody.appendChild( note );
		}
	}

	/* --- receive selection from the overlay ------------------------------ */

	window.addEventListener( 'message', function ( e ) {
		if ( e.origin !== ORIGIN || ! e.data || 'object' !== typeof e.data ) {
			return;
		}
		var msg = e.data;
		if ( 'ready' === msg.s5 ) {
			// Overlay is live; make sure it matches the current lens.
			sendToFrame( { s5: 's5-lens', lens: shell.state.lens } );
			// reloadPreview() (after a disable/enable or save round-trip) does a full
			// contentWindow.location.reload() — the old DOM, and with it the floating
			// selection toolbar, is gone. Without this the user has to click the
			// element again to see the toggle actually take effect ("delayed,
			// have to click out and back" — defect #6). Re-select the same node so
			// the toolbar (with its now-correct enable/disable icon) reappears
			// automatically once the fresh overlay reports ready.
			if ( selected && selected.node ) {
				sendToFrame( { s5: 's5-select-node', node: selected.node } );
			}
			return;
		}
		if ( 'select' === msg.s5 ) {
			selected = msg;
			// Flip the left panel from palette to the props editor (palette⇄props
			// swap, HANDOFF §2.3). Content-tab fields render below.
			if ( shell.showProps ) {
				shell.showProps( msg.label || msg.type || 'Element', msg.node || '' );
			}
			renderFields( msg );
		} else if ( 's5-focus-props' === msg.s5 ) {
			// Selection-chrome pencil: make sure the Content tab is shown.
			var contentTab = root.querySelector( '[data-s5-ptab="content"]' );
			if ( contentTab ) {
				contentTab.click();
			}
		} else if ( 's5-disable' === msg.s5 && msg.node ) {
			// Selection-chrome disable/enable (R4): set data-disabled through the ONE
			// door (mode:disable). The compiler drops the subtree from render + mirror
			// when disabled=true; it stays in canonical so it can be re-enabled.
			// Bug fix: this used to hardcode `true`, so the toolbar's "enable" (eye)
			// button — which posts disabled:false — silently re-disabled an already-
			// disabled element instead of re-enabling it. Pass the message's actual
			// intent through.
			doDisable( msg.node, !! msg.disabled );
		} else if ( 's5-duplicate' === msg.s5 && msg.node ) {
			// Duplicate is a re-keying server op (like insert); it lands with the
			// component/duplicate work. Surface it honestly rather than no-op silently.
			showDiagnostics( [ { message: 'Duplicate is coming with the component tools — use the palette to insert another, or Code lens to copy the block.' } ] );
		}
	} );

	/* --- disable a node through the one door (mode:disable) --------------- */

	function doDisable( node, disabled ) {
		if ( ! cfg.saveUrl || ! node ) {
			return;
		}
		fetch( cfg.saveUrl, {
			method: 'POST',
			credentials: 'same-origin',
			headers: {
				'Content-Type': 'application/json',
				'X-WP-Nonce': cfg.nonce || '',
			},
			body: JSON.stringify( { mode: 'disable', node: node, disabled: !! disabled } ),
		} )
			.then( function ( r ) {
				return r.json().then( function ( body ) {
					return { status: r.status, body: body };
				} );
			} )
			.then( function ( res ) {
				if ( res.body && res.body.ok ) {
					reloadPreview();
				} else {
					showDiagnostics( res.body && res.body.diagnostics );
				}
			} )
			.catch( function () {
				showDiagnostics( [ { message: 'Network error disabling the element.' } ] );
			} );
	}

	// Keep the overlay's lens state in sync when the user toggles Edit/Code.
	root.querySelectorAll( '[data-s5-lens]' ).forEach( function ( btn ) {
		btn.addEventListener( 'click', function () {
			sendToFrame( { s5: 's5-lens', lens: btn.getAttribute( 'data-s5-lens' ) } );
		} );
	} );

	/* --- Update: POST staged slot edits to the ONE save door ------------- */

	function doSave() {
		var edits = Object.keys( slotEdits ).map( function ( k ) {
			return slotEdits[ k ];
		} );
		if ( ! edits.length || ! cfg.saveUrl ) {
			return;
		}

		updateBtn.disabled = true;
		updateBtn.textContent = 'Saving…';

		fetch( cfg.saveUrl, {
			method: 'POST',
			credentials: 'same-origin',
			headers: {
				'Content-Type': 'application/json',
				'X-WP-Nonce': cfg.nonce || '',
			},
			body: JSON.stringify( { mode: 'slots', slots: edits } ),
		} )
			.then( function ( r ) {
				return r.json().then( function ( body ) {
					return { status: r.status, body: body };
				} );
			} )
			.then( function ( res ) {
				updateBtn.textContent = 'Update';
				if ( res.body && res.body.ok ) {
					slotEdits = {};
					shell.markClean();
					reloadPreview();
				} else {
					showDiagnostics( res.body && res.body.diagnostics );
					updateBtn.disabled = false;
				}
			} )
			.catch( function () {
				updateBtn.textContent = 'Update';
				updateBtn.disabled = false;
				showDiagnostics( [ { severity: 'error', message: 'Network error saving.' } ] );
			} );
	}

	function reloadPreview() {
		var f = shell.getPreviewFrame();
		if ( f ) {
			// Reload from the server so derived state (compiler output) replaces
			// the client feedback patches — the iframe is a projection, not state.
			f.contentWindow.location.reload();
		}
	}

	function showDiagnostics( diags ) {
		var box = el( 'div', { class: 's5e-diagnostics' } );
		box.appendChild( el( 'div', { class: 'field-label' }, 'Save rejected' ) );
		( diags || [] ).forEach( function ( d ) {
			var line = ( d.rule ? '[' + d.rule + '] ' : '' ) + ( d.message || '' ) +
				( d.token ? ' — token: ' + d.token : '' );
			box.appendChild( el( 'p', { class: 's5e-diag' }, line ) );
		} );
		panelBody.insertBefore( box, panelBody.firstChild );
	}

	if ( updateBtn ) {
		updateBtn.addEventListener( 'click', doSave );
	}
}() );
